#!/usr/bin/env python3
"""SPS_real_malumotlar_bazasi.xlsx, 6-varaq (fasad termopanel katalogi, 76 mahsulot)
-> data/termopanel-2027.json (GENERATED).

Bular tayyor fasad mahsulotlari (penoplast asos + travertin/mramor qoplama), qolip emas.
`npm run catalog:import` ularni bazaga **qoralama** (draft) sifatida qo'shadi:
rasm va tarjimalar admin'da to'ldirilgach "Nashr" qilinadi. Raqam o'ylab topilmaydi.
"""
import json, re, sys
from pathlib import Path
import openpyxl

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'docs/design-handoff/data-sources/SPS_real_malumotlar_bazasi.xlsx'
OUT = ROOT / 'data/termopanel-2027.json'

KIND = {
    'TP': ('termopanel', 'Termopanel'),
    'FSD': ('fasad_dekor', 'Dekor panel'),
    'BP': ('fasad_dekor', 'Beeline panel'),
    'NL': ('fasad_dekor', 'Tyaga'),
    'KRN': ('fasad_dekor', 'Karniz'),
    'PL': ('fasad_dekor', 'Pilyastra'),
    'KPL': ('fasad_dekor', 'Kapitel baza'),
    'SL': ('fasad_dekor', 'Sokol'),
}

def slugify(s):
    s = s.lower().replace('×', 'x')
    s = re.sub(r"[^a-z0-9]+", '-', s)
    return s.strip('-')

def main():
    wb = openpyxl.load_workbook(SRC, read_only=True, data_only=True)
    ws = wb['6 SPS PLAST termopanel']
    items, seen = [], set()
    for row in list(ws.iter_rows(values_only=True))[3:]:
        code, title, size, page = (row + (None,) * 5)[:4]
        note = row[4] if len(row) > 4 else None
        if not code or not title:
            continue
        prefix = code.split('-')[0]
        section, kind = KIND.get(prefix, ('fasad_dekor', 'Fasad elementi'))
        slug = slugify(f'{code}-{title}')
        while slug in seen:
            slug += '-b'
        seen.add(slug)
        base = 'Penoplast yoki bazalt' if prefix == 'TP' else 'Penoplast'
        items.append({
            'code': code,
            'slug': slug,
            'section': section,
            'name': {'uz': title, 'ru': None, 'en': None},
            'subtitle': {'uz': kind, 'ru': None, 'en': None},
            'size': size,
            'specs': [
                {'k': {'uz': "O'lcham, mm", 'ru': 'Размер, мм', 'en': 'Size, mm'}, 'v': {'uz': size, 'ru': size, 'en': size}},
                {'k': {'uz': 'Asos', 'ru': 'Основа', 'en': 'Core'}, 'v': {'uz': base, 'ru': None, 'en': None}},
                {'k': {'uz': 'Qoplama', 'ru': 'Покрытие', 'en': 'Finish'}, 'v': {'uz': 'Travertin / Mramor', 'ru': 'Травертин / Мрамор', 'en': 'Travertine / Marble'}},
            ],
            'source': f'xlsx 6-varaq, katalog beti {page}' + (f' — {note}' if note else ''),
        })
    OUT.write_text(json.dumps({'$comment': 'GENERATED by scripts/extract/build_termopanel_2027.py — do not edit', 'items': items}, ensure_ascii=False, indent=1) + '\n')
    print(f'{len(items)} ta mahsulot -> {OUT.relative_to(ROOT)}')

if __name__ == '__main__':
    sys.exit(main())
