#!/usr/bin/env python3
"""3D katalog (public/3d/<id>/index.html) -> data/catalog3d-2027.json.

3D paketlar (QR sahifalar, PR #35/#36/#42) biznesning to'liq mahsulot ro'yxatini
o'z ichiga oladi: 206 ta mahsulot, ruscha nom, oila, o'lcham va qolip chuqurligi,
hamda renderlar (qolip_tik.jpg — qolip, r_04/r_05 — obyektdagi sahna, r_03 — tayyor
element, r_10..r_12 — qo'shimcha sahnalar). `thumb.jpg` — normal-map (texnik tekstura),
rasm sifatida ISHLATILMAYDI.

Natija faqat o'qiladi; tahrirlash kerak bo'lsa manba sahifalarni yangilang.
"""
from __future__ import annotations

import html
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "public/3d")
OUT = os.path.join(ROOT, "data/catalog3d-2027.json")

FAMILY = {
    "Тротуарная плитка": "trotuar",
    "Фасад": "fasad",
    "Заборы": "zabor",
    "Декоративные панели": "dekor",
    "Скамейки": "skameyka",
}


def mm(text: str) -> str | None:
    m = re.search(r"([\d×x]+)\s*мм", text)
    return m.group(1).replace("x", "×") if m else None


def parse(pid: str) -> dict | None:
    path = os.path.join(SRC, pid, "index.html")
    if not os.path.isfile(path):
        return None
    s = open(path, encoding="utf-8").read()
    k = re.search(r'<div class="k">([^<]*)</div>', s)
    h1 = re.search(r"<h1>([^<]*)</h1>", s)
    if not k or not h1:
        return None
    family_ru, _, label = html.unescape(k.group(1)).partition(" · ")
    spans = dict(
        (html.unescape(a).strip(), html.unescape(b).strip())
        for a, b in re.findall(r"<span>([^<]*)<b>([^<]*)</b></span>", s)
    )
    files = sorted(os.listdir(os.path.join(SRC, pid)))
    return {
        "id": pid,
        "family": FAMILY.get(family_ru.strip(), None),
        "familyRu": family_ru.strip(),
        "label": label.strip(),
        "nameRu": html.unescape(h1.group(1)).strip(),
        "size": mm(spans.get("Размер", "")),
        "depth": (mm(spans.get("Глубина формы", "")) or "").split("×")[0] or None,
        "renders": [f[:-4] for f in files if f.endswith(".jpg") and f != "thumb.jpg"],
        "glb": [f[:-4] for f in files if f.endswith(".glb")],
    }


def main() -> None:
    items = []
    for pid in sorted(os.listdir(SRC)):
        row = parse(pid)
        if row:
            if row["family"] is None:
                raise SystemExit(f"{pid}: noma'lum oila {row['familyRu']!r}")
            items.append(row)
    out = {
        "$comment": "GENERATED by scripts/extract/build_3d_catalog_2027.py from public/3d/*/index.html. Do not edit.",
        "items": items,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
        f.write("\n")
    by: dict[str, int] = {}
    for r in items:
        by[r["family"]] = by.get(r["family"], 0) + 1
    print(f"catalog3d: {len(items)} ta mahsulot {by}")


if __name__ == "__main__":
    main()
